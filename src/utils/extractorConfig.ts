import { AudioExtractorConfig } from '../types';

const EXTRACTOR_STORAGE_KEY = 'casttube_extractor_config_v1';

export function loadExtractorConfig(): AudioExtractorConfig {
  try {
    const raw = localStorage.getItem(EXTRACTOR_STORAGE_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw) as AudioExtractorConfig;
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

export function saveExtractorConfig(config: AudioExtractorConfig): void {
  try {
    const hasValue = Boolean(
      config.oauthTokens?.access_token || config.cookies?.trim() || config.extractorUrl?.trim()
    );
    if (!hasValue) {
      localStorage.removeItem(EXTRACTOR_STORAGE_KEY);
      return;
    }
    localStorage.setItem(
      EXTRACTOR_STORAGE_KEY,
      JSON.stringify({
        ...config,
        updatedAt: new Date().toISOString(),
      })
    );
  } catch {
    // ignore storage quota errors
  }
}

export function clearExtractorConfig(): void {
  try {
    localStorage.removeItem(EXTRACTOR_STORAGE_KEY);
  } catch {
    // ignore
  }
}

function toBase64Url(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  for (let i = 0; i < bytes.length; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

export function normalizeClientCookies(rawInput: string | undefined): string {
  if (!rawInput) return '';
  const trimmed = rawInput.trim();
  if (!trimmed) return '';

  const lines = trimmed.split(/\r?\n/);
  const hasNetscape = lines.some((line) => {
    const l = line.trim();
    return l && !l.startsWith('#') && l.split('\t').length >= 7;
  });

  if (hasNetscape) {
    const pairs: string[] = [];
    const seen = new Set<string>();
    for (const line of lines) {
      const l = line.trim();
      if (!l || l.startsWith('#')) continue;
      const cols = line.split('\t');
      if (cols.length < 7) continue;
      const domain = (cols[0] || '').toLowerCase();
      if (domain && !domain.includes('youtube.com') && !domain.includes('google.com')) continue;
      const name = (cols[5] || '').trim();
      const value = (cols[6] || '').trim();
      if (!name || !value || seen.has(name)) continue;
      seen.add(name);
      pairs.push(`${name}=${value}`);
    }
    return pairs.join('; ');
  }

  return trimmed
    .replace(/^cookie:\s*/i, '')
    .replace(/[\r\n]+/g, '; ')
    .trim();
}

export function buildExtractorHeaders(configOverride?: AudioExtractorConfig): Record<string, string> {
  const cfg = configOverride || loadExtractorConfig();
  const headers: Record<string, string> = {};

  if (cfg.oauthTokens?.access_token) {
    try {
      headers['X-YouTube-OAuth'] = toBase64Url(JSON.stringify(cfg.oauthTokens));
    } catch {
      // ignore
    }
  }

  if (cfg.cookies) {
    const normalized = normalizeClientCookies(cfg.cookies).replace(/[^\x20-\x7E]/g, '');
    if (normalized) {
      headers['X-YouTube-Cookies'] = normalized;
    }
  }

  if (cfg.extractorUrl) {
    const cleanUrl = cfg.extractorUrl.trim().replace(/\/+$/, '');
    if (/^https?:\/\//i.test(cleanUrl)) {
      headers['X-Extractor-Url'] = cleanUrl;
    }
  }

  return headers;
}

export function isLoggedInYouTubeCookies(cookies: string | undefined): boolean {
  if (!cookies) return false;
  return /(?:^|;\s*)(SAPISID|SID|__Secure-1PSID|__Secure-3PSID)=/i.test(cookies);
}

export function isAutoGuestCookies(cookies: string | undefined): boolean {
  return Boolean(cookies?.trim() && !isLoggedInYouTubeCookies(cookies));
}

let activeExtractorSyncPromise: Promise<void> | null = null;
let pendingAutoCookiePromise: Promise<{
  config: AudioExtractorConfig;
  autoGenerated: boolean;
  verification?: { available: boolean; status: string; reason?: string };
}> | null = null;

export async function ensureAutoYouTubeCookies(options?: {
  force?: boolean;
  verify?: boolean;
  testVideoId?: string;
}): Promise<{
  config: AudioExtractorConfig;
  autoGenerated: boolean;
  verification?: { available: boolean; status: string; reason?: string };
}> {
  const force = Boolean(options?.force);
  const current = loadExtractorConfig();

  if (!force && (current.cookies?.trim() || current.oauthTokens?.access_token)) {
    return { config: current, autoGenerated: false };
  }

  if (!force && pendingAutoCookiePromise) {
    return pendingAutoCookiePromise;
  }

  const run = async () => {
    try {
      const res = await fetch('/api/youtube/extractor-auth', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Accept: 'application/json',
          ...buildExtractorHeaders(current),
        },
        body: JSON.stringify({
          action: 'auto_cookie',
          force,
          verify: Boolean(options?.verify),
          testVideoId: options?.testVideoId,
        }),
      });
      if (!res.ok) {
        return { config: loadExtractorConfig(), autoGenerated: false };
      }
      const data = (await res.json()) as {
        ok?: boolean;
        cookies?: string | null;
        autoGenerated?: boolean;
        oauthTokens?: AudioExtractorConfig['oauthTokens'];
        extractorUrl?: string | null;
        verification?: { available: boolean; status: string; reason?: string };
      };
      const latest = loadExtractorConfig();
      if (data?.cookies) {
        const nextConfig: AudioExtractorConfig = {
          ...latest,
          cookies: normalizeClientCookies(data.cookies),
          oauthTokens: data.oauthTokens || latest.oauthTokens,
          extractorUrl: data.extractorUrl || latest.extractorUrl,
        };
        saveExtractorConfig(nextConfig);
        return {
          config: nextConfig,
          autoGenerated: Boolean(data.autoGenerated ?? true),
          verification: data.verification,
        };
      }
      return {
        config: latest,
        autoGenerated: false,
        verification: data?.verification,
      };
    } catch {
      return { config: loadExtractorConfig(), autoGenerated: false };
    }
  };

  if (force) {
    return run();
  }

  const task = run().finally(() => {
    if (pendingAutoCookiePromise === task) {
      pendingAutoCookiePromise = null;
    }
  });
  pendingAutoCookiePromise = task;
  return task;
}

export async function syncExtractorConfigToServer(
  configOverride?: AudioExtractorConfig
): Promise<void> {
  if (!configOverride && activeExtractorSyncPromise) {
    return activeExtractorSyncPromise;
  }

  const cfg = configOverride || loadExtractorConfig();
  if (!cfg.oauthTokens?.access_token && !cfg.cookies && !cfg.extractorUrl) return;

  const runSync = async (): Promise<void> => {
    try {
      const res = await fetch('/api/youtube/extractor-auth', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'restore',
          oauthTokens: cfg.oauthTokens,
          cookies: cfg.cookies,
          extractorUrl: cfg.extractorUrl,
        }),
      });
      if (res.ok) {
        const data = await res.json();
        if (data?.oauthTokens && data.oauthTokens.access_token !== cfg.oauthTokens?.access_token) {
          saveExtractorConfig({
            ...cfg,
            oauthTokens: data.oauthTokens,
          });
        }
      } else if (res.status >= 400 && res.status < 500 && !configOverride) {
        clearExtractorConfig();
      }
    } catch {
      // non-fatal background sync
    }
  };

  if (configOverride) {
    return runSync();
  }

  const task = runSync().finally(() => {
    if (activeExtractorSyncPromise === task) {
      activeExtractorSyncPromise = null;
    }
  });
  activeExtractorSyncPromise = task;
  return task;
}

export async function tryClientDirectExtractor(
  videoId: string,
  extractorUrl?: string,
  signal?: AbortSignal
): Promise<{ url: string; mimeType: string } | null> {
  const cleanBase = extractorUrl?.trim().replace(/\/+$/, '');
  if (!cleanBase || !/^https?:\/\//i.test(cleanBase)) return null;

  // 1. Try Cobalt API from browser IP
  try {
    const res = await fetch(`${cleanBase}/`, {
      method: 'POST',
      signal,
      headers: {
        'Content-Type': 'application/json',
        Accept: 'application/json',
      },
      body: JSON.stringify({
        url: `https://www.youtube.com/watch?v=${videoId}`,
        downloadMode: 'audio',
        audioFormat: 'best',
      }),
    });
    if (res.ok) {
      const data = await res.json();
      if ((data?.status === 'tunnel' || data?.status === 'redirect') && typeof data?.url === 'string') {
        return { url: data.url, mimeType: 'audio/mp4' };
      }
    }
  } catch {
    // continue
  }

  // 2. Try Piped API from browser IP
  try {
    const res = await fetch(`${cleanBase}/streams/${encodeURIComponent(videoId)}`, {
      signal,
      headers: { Accept: 'application/json' },
    });
    if (res.ok) {
      const data = await res.json();
      const streams: Array<{ url?: string; mimeType?: string }> = Array.isArray(data?.audioStreams)
        ? data.audioStreams
        : [];
      const picked =
        streams.find((s) => s?.url && String(s.mimeType || '').includes('audio/mp4')) ||
        streams.find((s) => s?.url && String(s.mimeType || '').startsWith('audio/'));
      if (picked?.url) {
        return {
          url: picked.url,
          mimeType: String(picked.mimeType || 'audio/mp4').split(';')[0].trim(),
        };
      }
    }
  } catch {
    // continue
  }

  return null;
}
